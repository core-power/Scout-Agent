def esc(s):
    # 转义为 JS 字符串字面量：\\ 与 " 之外，还必须把真实换行/回车/制表符转为 \\n \\r \\t 字面量，
    # 否则多行文本会生成真实换行导致 i18n.js 语法错误（SyntaxError: Invalid or unexpected token）
    return (s.replace('\\', '\\\\')
             .replace('"', '\\"')
             .replace('\r\n', '\\n')
             .replace('\n', '\\n')
             .replace('\r', '\\n')
             .replace('\t', '\\t'))

def build_block(entries):
    lines = []
    for zh, en in sorted(entries.items(), key=lambda x: x[0]):
        lines.append(f'    "{esc(zh)}": {{ zh: "{esc(zh)}", en: "{esc(en)}" }},')
    return "\n".join(lines)

def main():
    path = "scout/web/static/i18n.js"
    src = open(path, encoding="utf-8").read()
    # 已有键
    have = set(re.findall(r'"([^"]+)":\s*\{\s*zh:', src))
    new = {zh: en for zh, en in M.items() if zh not in have}
    if not new:
        print("无新增条目")
        return
    block = "\n" + build_block(new) + "\n"
    # 插入到字典结束 }; 前（最后一条 "⚠️ 未配置 API Key" 之后）
    marker = '"⚠️ 未配置 API Key": { zh: "⚠️ 未配置 API Key", en: "⚠️ API Key not configured" },'
    if marker not in src:
        print("未找到插入锚点"); sys.exit(1)
    src = src.replace(marker, marker + block, 1)
    open(path, "w", encoding="utf-8").write(src)
    print(f"已插入 {len(new)} 条新字典条目")

if __name__ == "__main__":
    main()
